# ---------------------------------------------------------------- Part 2a: city valuation
def city_scores(cfg, verbose=True):
    rb = cfg["rent_vs_buy"]; a, w = rb["anchors"], rb["weights"]
    hl, inc, yrs = rb["home_loan"], rb["income_cagr"], rb["years_2019_to_q2_2026"]
    rows = []
    for city, c in rb["cities"].items():
        cagr = ((1 + c["px_gain_2019_q2_2026"]/100)**(1/yrs) - 1)*100
        x = {"R3": c["rent_yield"] - hl, "R4": c["rent_yield"], "R5": cagr - inc}
        s = {k: ind_score(a[k][0], a[k][1], v) for k, v in x.items()}
        sc = sum(w[k]*s[k] for k in s)/sum(w.values())
        rows.append({"city": city, "valuation_score": round(sc, 1), "valuation_read": val_band(sc),
                     "rent_yield_pct": c["rent_yield"], "rent_minus_loan_pp": round(x["R3"], 2),
                     "price_cagr_2019_26_pct": round(cagr, 1), "price_minus_income_pp": round(x["R5"], 1),
                     "R3": round(s["R3"], 0), "R4": round(s["R4"], 0), "R5": round(s["R5"], 0),
                     "stamp_reg_pct": c["stamp_reg_pct"], "source": c["src"]})
    out = pd.DataFrame(rows).sort_values("valuation_score").reset_index(drop=True)
    out.to_csv(CITY_LOG, index=False)
    if verbose:
        print(f"\nRESIDENTIAL PROPERTY BY CITY — valuation (same anchors as asset-classes RESI_RE; home loan {hl}%, income CAGR {inc}%)")
        print(out[["city", "valuation_score", "valuation_read", "rent_yield_pct", "rent_minus_loan_pp",
                   "price_cagr_2019_26_pct", "price_minus_income_pp", "R3", "R4", "R5"]].to_string(index=False))
    return out


# ---------------------------------------------------------------- Part 2b: rent vs buy
def emi(P, r_m, n):
    return P/n if r_m == 0 else P*r_m*(1 + r_m)**n/((1 + r_m)**n - 1)


def rent_vs_buy(p, price_growth=None):
    """p: dict of scenario inputs (defaults already merged). Returns dict of results."""
    g = p["price_growth"] if price_growth is None else price_growth
    price, rent0, H = p["price"], p["rent"], int(round(p["hold_yrs"]*12))
    r_alt = (1 + p["alt_return"]/100)**(1/12) - 1
    # --- buyer upfront
    down = price*p["down_payment_pct"]/100; loan = price - down
    stamp = price*p["stamp_reg_pct"]/100 + p.get("stamp_reg_fixed", 0)
    upfront = down + stamp + price*p["buy_brokerage_pct"]/100 + price*p["gst_pct"]/100
    rm = p["loan_rate"]/1200; n = int(p["tenure_yrs"]*12); E = emi(loan, rm, n) if loan > 0 else 0
    # --- renter starts with the same cash: deposit + invested pool
    deposit = rent0*p["deposit_months"]
    pool = upfront - deposit; pool_cost = pool       # cost basis of renter's investments
    bal = loan; val = price; rent = rent0; tax_saved_total = 0.0
    yr_int = yr_prin = 0.0; buy_out_total = rent_out_total = 0.0
    for m in range(1, H + 1):
        if m > 1 and (m - 1) % 12 == 0:
            rent *= 1 + p["rent_growth"]/100
        val_start_year = price*(1 + g/100)**((m - 1)//12)
        interest = bal*rm; prin = min(E - interest, bal) if bal > 0 else 0
        bal -= prin; yr_int += interest; yr_prin += prin
        own = (E if prin > 0 or interest > 0 else 0) + val_start_year*(p["maintenance_pct"] + p["property_tax_pct"])/1200
        rent_cost = rent*(1 + p["rent_brokerage_months_per_yr"]/12)
        tax_back = 0.0
        if m % 12 == 0:   # year-end tax effects
            if p["tax_regime"] == "old":
                tax_back = min(yr_int, 200000)*p["slab"]
                if p["use_80c"]: tax_back += min(yr_prin, 150000)*p["slab"]
                tax_back -= p["hra_tax_saving_per_yr"]          # renter's HRA saving lost by buying
            yr_int = yr_prin = 0.0
        own_net = own - tax_back; tax_saved_total += tax_back
        buy_out_total += own_net; rent_out_total += rent_cost
        diff = own_net - rent_cost          # renter invests what the owner spends extra (or draws if negative)
        pool = pool*(1 + r_alt) + diff; pool_cost += diff
    sale = price*(1 + g/100)**p["hold_yrs"]
    sell_cost = sale*p["sell_cost_pct"]/100
    cost_basis = price + stamp + price*p["buy_brokerage_pct"]/100 + price*p["gst_pct"]/100
    gain = sale - sell_cost - cost_basis
    cgt = 0.0
    if gain > 0:
        cgt = gain*(0.125*1.04 if p["hold_yrs"] > 2 else p["slab"])
    buyer = sale - sell_cost - bal - cgt
    renter_gain = pool - pool_cost
    renter = pool - max(renter_gain, 0)*p["alt_tax"] + deposit
    return {"buyer_net": buyer, "renter_net": renter, "gap": renter - buyer, "upfront": upfront, "emi": E,
            "loan_left": bal, "sale": sale, "cgt": cgt, "tax_saved": tax_saved_total,
            "buy_outgo_m1": E + price*(p["maintenance_pct"] + p["property_tax_pct"])/1200, "rent_m1": rent0,
            "pool": pool}


def breakeven_growth(p):
    lo, hi = -10.0, 30.0
    if rent_vs_buy(p, hi)["gap"] > 0: return None
    if rent_vs_buy(p, lo)["gap"] < 0: return lo
    for _ in range(60):
        mid = (lo + hi)/2
        if rent_vs_buy(p, mid)["gap"] > 0: lo = mid
        else: hi = mid
    return (lo + hi)/2


def rb_score(gap_pct):
    """Renter's advantage as % of price -> 1 (buy clearly better, -15%) .. 100 (rent clearly better, +25%)."""
    return ind_score(-15, 25, gap_pct)


def rb_read(x):
    return ("BUY clearly better" if x <= 20 else "Buy better" if x <= 35 else "Close, lean buy" if x <= 50
            else "Close, lean rent" if x <= 65 else "Rent better" if x <= 80 else "RENT clearly better")


def merge_scenario(cfg, sc):
    rb = cfg["rent_vs_buy"]; p = dict(rb["defaults"]); p.update({k: v for k, v in sc.items() if k != "note"})
    city = rb["cities"].get(p.get("city"), {})
    p.setdefault("stamp_reg_pct", city.get("stamp_reg_pct", 7.0))
    p.setdefault("stamp_reg_fixed", city.get("stamp_reg_fixed", 0))
    if "rent" not in p and city:
        p["rent"] = p["price"]*city["rent_yield"]/1200
    return p


def run_rentbuy(cfg, scenarios, verbose=True):
    rows = []
    for name, sc in scenarios.items():
        p = merge_scenario(cfg, sc)
        r = rent_vs_buy(p); be = breakeven_growth(p)
        gap_pct = r["gap"]/p["price"]*100; s = rb_score(gap_pct)
        sens = {}
        for gg in (0, 3, 6, 9):
            for hh in (3, 5, 10):
                q = dict(p); q["hold_yrs"] = hh
                sens[f"g{gg}_h{hh}"] = round(rent_vs_buy(q, gg)["gap"]/1e5, 1)
        rows.append({"scenario": name, "city": p.get("city"), "price": p["price"], "rent": round(p["rent"]),
                     "gross_rent_yield_pct": round(p["rent"]*1200/p["price"], 2), "hold_yrs": p["hold_yrs"],
                     "loan_rate": p["loan_rate"], "down_pct": p["down_payment_pct"], "price_growth": p["price_growth"],
                     "rent_growth": p["rent_growth"], "alt_return": p["alt_return"], "tax_regime": p["tax_regime"],
                     "upfront": round(r["upfront"]), "emi": round(r["emi"]), "own_cost_m1": round(r["buy_outgo_m1"]),
                     "buyer_net_lakh": round(r["buyer_net"]/1e5, 1), "renter_net_lakh": round(r["renter_net"]/1e5, 1),
                     "rent_advantage_lakh": round(r["gap"]/1e5, 1), "rent_advantage_pct_price": round(gap_pct, 1),
                     "breakeven_price_growth": None if be is None else round(be, 2),
                     "score": round(s, 1), "read": rb_read(s), **{f"sens_{k}": v for k, v in sens.items()}})
        if verbose:
            print(f"\n=== RENT vs BUY: {name} ({p.get('city')}) — hold {p['hold_yrs']} yrs, {p['tax_regime']} tax regime")
            print(f"   price Rs {p['price']/1e5:,.1f} lakh · rent Rs {p['rent']:,.0f}/m (gross yield {p['rent']*1200/p['price']:.2f}%) · "
                  f"loan {100-p['down_payment_pct']:.0f}% at {p['loan_rate']}% for {p['tenure_yrs']} yrs · stamp+reg {p['stamp_reg_pct']}%")
            print(f"   upfront cash Rs {r['upfront']/1e5:,.1f} lakh · EMI Rs {r['emi']:,.0f} · month-1 owning cost Rs {r['buy_outgo_m1']:,.0f} vs rent Rs {p['rent']:,.0f}")
            print(f"   assumptions: price growth {p['price_growth']}%/yr, rent growth {p['rent_growth']}%/yr, renter's investments {p['alt_return']}%/yr pre-tax (tax {p['alt_tax']:.1%} on gains)")
            print(f"   net worth after {p['hold_yrs']} yrs: BUY Rs {r['buyer_net']/1e5:,.1f} lakh vs RENT Rs {r['renter_net']/1e5:,.1f} lakh "
                  f"-> {'renting' if r['gap'] > 0 else 'buying'} ahead by Rs {abs(r['gap'])/1e5:,.1f} lakh ({gap_pct:+.1f}% of price, + = rent better)")
            print(f"   break-even price growth: {'>30' if be is None else f'{be:.2f}'}%/yr · home-loan tax saved Rs {r['tax_saved']/1e5:,.1f} lakh · CGT on sale Rs {r['cgt']/1e5:,.1f} lakh")
            print(f"   SCORE {s:.1f} -> {rb_read(s)}  (1 = buy clearly better, 100 = rent clearly better)")
            print("   rent advantage, Rs lakh (rows = price growth %/yr, cols = hold yrs):")
            print("        " + "".join(f"{h:>8}" for h in (3, 5, 10)))
            for gg in (0, 3, 6, 9):
                print(f"   {gg:>3}% " + "".join(f"{sens[f'g{gg}_h{h}']:>8}" for h in (3, 5, 10)))
    out = pd.DataFrame(rows)
    out.to_csv(RB_LOG, index=False)
    return out


def parse_kv(args):
    sc = {}
    for a in args:
        k, v = a.split("=", 1)
        sc[k] = v if k in ("city", "tax_regime") else (v.lower() == "true" if k == "use_80c" else float(v))
    return sc


