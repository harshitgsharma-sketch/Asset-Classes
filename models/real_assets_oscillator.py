"""Real-Assets Model (INR investor) — v1, indicative — "Asset Mgmt" project.

Part 1 — Listed REITs, SM-REITs and InvITs: entry/exit oscillator per security, same engine as the
other project models:
  per-indicator score = clamp(1 + 99*(x - cheap)/(rich - cheap), 1, 100)   (high = expensive/headwind)
  weight W = Impact x Severity x Reliability x Stability; blanks skipped, weights re-normalised inside
  each bucket; a missing bucket drops out and the others are re-weighted; a bucket resting on a single
  live indicator moves only half-way from 50 (THIN_SHRINK).
  Buckets: V Valuation (yield spread vs 10-yr G-sec, price/NAV, yield level) 55% ·
           F Filter (distribution growth YoY, leverage) 25% · T Timing (repo path, 52-week position) 20%.
  Anchors are set per family (office REIT, retail REIT, SM-REIT, power InvIT, road InvIT).
Part 2 — Residential property:
  (a) city valuation score with the asset-class model's RESI_RE anchors (R3 rent yield - home loan,
      R4 rent yield, R5 price CAGR - income CAGR), so the two models agree;
  (b) rent-vs-buy calculator: month-by-month net-worth comparison over the holding period, with
      stamp duty, loan, maintenance, tax (old/new regime), selling cost, capital-gains tax and the
      renter investing the difference. Reports the gap, break-even price growth and a 1-100 score
      (1 = buying clearly better, 100 = renting clearly better).

Files (project, under claude/):
  real-assets-config.json              families, anchors, securities, tax, city defaults
  real-assets-inputs-monthly.csv       long format: one row per (month, security) + a MACRO row
  real-assets-rentbuy-scenarios.json   saved rent-vs-buy scenarios (user inputs)
  real-assets-score-log.csv            Part 1 output (regenerated)
  real-assets-city-log.csv             Part 2a output (regenerated)
  real-assets-rentbuy-log.csv          Part 2b output (regenerated by `rentbuy`)
Usage:
  python3 real_assets_oscillator.py [all|table|drivers|chart|cities] [KEY ...]
  python3 real_assets_oscillator.py rentbuy [SCENARIO ...]            (saved scenarios; default all)
  python3 real_assets_oscillator.py rentbuy city=Pune price=9000000 rent=28000 hold_yrs=5 tax_regime=old
"""
import json, sys, math
import pandas as pd

CONFIG, INPUTS = "real-assets-config.json", "real-assets-inputs-monthly.csv"
LOG, CITY_LOG, RB_LOG = "real-assets-score-log.csv", "real-assets-city-log.csv", "real-assets-rentbuy-log.csv"
SCEN, CHART = "real-assets-rentbuy-scenarios.json", "real-assets-scores.png"
THIN_SHRINK = 0.5
BUCKET_NAME = {"V": "Valuation", "F": "Filter", "T": "Timing"}


def num(v):
    try:
        f = float(v); return None if math.isnan(f) else f
    except (TypeError, ValueError):
        return None


def ind_score(c, r, x):
    return max(1.0, min(100.0, 1 + 99*(x - c)/(r - c)))


def band(x):
    return ("STRONG BUY" if x <= 20 else "BUY" if x <= 35 else "ACCUMULATE" if x <= 50
            else "HOLD" if x <= 65 else "TRIM" if x <= 80 else "EXIT")


def val_band(x):
    return ("Very cheap" if x <= 20 else "Cheap" if x <= 35 else "Fair, cheap side" if x <= 50
            else "Fair, rich side" if x <= 65 else "Expensive" if x <= 80 else "Very expensive")


# ---------------------------------------------------------------- Part 1: listed REITs / InvITs
def derive(row, macro):
    """Raw columns -> indicator values (None when an input is blank)."""
    out = {}
    p, nav, dq = num(row.get("price")), num(row.get("nav")), num(row.get("dpu_q"))
    g10 = num(macro.get("gsec10"))
    y = 400*dq/p if None not in (p, dq) and p else None          # latest quarter DPU annualised / price, %
    out["_yield"] = y
    if y is not None:
        out["V3"] = y
        if g10 is not None: out["V1"] = y - g10
    if None not in (p, nav) and nav: out["V2"] = p/nav
    yoy, ly = num(row.get("dpu_yoy")), num(row.get("dpu_q_ly"))
    if yoy is None and None not in (dq, ly) and ly: yoy = (dq/ly - 1)*100
    if yoy is not None: out["F1"] = yoy
    if num(row.get("ltv")) is not None: out["F2"] = num(row.get("ltv"))
    r, re = num(macro.get("repo")), num(macro.get("repo_exp1y"))
    if None not in (r, re): out["T1"] = (re - r)*100
    hi, lo = num(row.get("hi52")), num(row.get("lo52"))
    if None not in (p, hi, lo) and hi > lo: out["T2"] = min(max((p - lo)/(hi - lo), 0), 1)*100
    return out


def score_security(sec, fam, ind_cfg, bw, vals):
    buckets, drivers = {}, []
    for b in bw:
        n_ = d_ = 0.0; live = []
        for iid, ic in ind_cfg.items():
            if ic["bucket"] != b or iid not in vals: continue
            c, r = fam["anchors"][iid]
            w = ic["I"]*ic["S"]*ic["R"]*ic["St"]
            s = ind_score(c, r, vals[iid]); n_ += w*s; d_ += w
            live.append({"id": iid, "name": ic["name"], "type": ic["type"], "value": round(vals[iid], 2),
                         "unit": ic["unit"], "score": round(s, 1), "w": w, "bucket": b})
        if not d_: continue
        sc = n_/d_; thin = len(live) == 1
        if thin: sc = 50 + (sc - 50)*THIN_SHRINK
        for dd in live: dd["_bw"] = dd["w"]/d_*(THIN_SHRINK if thin else 1)
        buckets[b] = sc; drivers += live
    if not buckets: return None
    tot = sum(bw[b] for b in buckets)
    osc = sum(bw[b]*buckets[b] for b in buckets)/tot
    for dd in drivers:
        dd["pull"] = round(bw[dd["bucket"]]/tot*dd["_bw"]*(dd["score"] - 50), 2)
    return {"osc": osc, "buckets": buckets, "drivers": drivers, "live": len(drivers), "n": len(ind_cfg)}


def run(keys=None, verbose=True):
    cfg = json.load(open(CONFIG))
    df = pd.read_csv(INPUTS, dtype={"month": str})
    fams, ind_cfg, bw = cfg["families"], cfg["indicators"], cfg["bucket_weights"]
    slab = cfg["tax"]["slab_incl_cess"]
    rows = []
    for month, g in df.groupby("month"):
        macro = g[g.key == "MACRO"].iloc[0].to_dict() if (g.key == "MACRO").any() else {}
        for sec in cfg["securities"]:
            m = g[g.key == sec["key"]]
            if m.empty: continue
            row = m.iloc[0].to_dict(); fam = fams[sec["family"]]
            vals = derive(row, macro)
            s = score_security(sec, fam, ind_cfg, bw, vals)
            if s is None: continue
            flags = list(sec.get("flags", []))
            if s["osc"] <= 35 and s["buckets"].get("F", 0) >= 70:
                flags.append("falling knife: Buy vetoed (Filter >= 70)")
            if vals.get("V2") is None: flags.append("no NAV: price/NAV missing")
            ts = num(row.get("taxable_share")); ts_est = ts is None
            if ts is None: ts = fam["taxable_share_default"]
            y = vals.get("_yield")
            post = None if y is None else y*(1 - slab*ts)
            sig = band(s["osc"])
            if "Buy vetoed" in " ".join(flags): sig = "ACCUMULATE (veto)"
            rows.append({"month": month, "key": sec["key"], "name": sec["name"], "family": fam["label"],
                         "oscillator": round(s["osc"], 1), "signal": sig,
                         "valuation": round(s["buckets"]["V"], 1) if "V" in s["buckets"] else None,
                         "filter": round(s["buckets"]["F"], 1) if "F" in s["buckets"] else None,
                         "timing": round(s["buckets"]["T"], 1) if "T" in s["buckets"] else None,
                         "valuation_read": val_band(s["buckets"]["V"]) if "V" in s["buckets"] else None,
                         "dist_yield_pct": None if y is None else round(y, 2),
                         "spread_vs_gsec_pp": None if vals.get("V1") is None else round(vals["V1"], 2),
                         "price_to_nav": None if vals.get("V2") is None else round(vals["V2"], 2),
                         "dpu_yoy_pct": None if vals.get("F1") is None else round(vals["F1"], 1),
                         "post_tax_yield_pct": None if post is None else round(post, 2),
                         "taxable_share": round(ts, 2), "taxable_share_est": ts_est,
                         "mcap_cr": num(row.get("mcap_cr")),
                         "indicators_live": f"{s['live']}/{s['n']}",
                         "drivers": "; ".join(f"{d['id']} {d['value']}{d['unit'] if d['unit'] in ('%','x') else ' '+d['unit']}->{d['score']:.0f}" for d in s["drivers"]),
                         "flags": " | ".join(flags)})
            if verbose and month == df.month.max() and (not keys or sec["key"] in keys):
                bstr = " ".join(f"{b}={s['buckets'][b]:.1f}" for b in ("V", "F", "T") if b in s["buckets"])
                print(f"\n=== {sec['name']} ({sec['key']}, {fam['label']}) {month}: OSCILLATOR {s['osc']:.1f} -> {sig} | {bstr} | "
                      f"live {s['live']}/{s['n']} | yield {y:.2f}% (post-tax {post:.2f}% at {slab:.1%} slab, taxable share {ts:.2f}{' est.' if ts_est else ''})")
                for d in sorted(s["drivers"], key=lambda d: -d["pull"]):
                    print(f"   {d['id']:<3} {d['name']:<46} {d['type']:<10} value={d['value']:<9} {d['unit']:<3} score={d['score']:>5}  pull={d['pull']:+.2f}")
                for f in flags: print(f"   flag: {f}")
    log = pd.DataFrame(rows).sort_values(["month", "oscillator"]).reset_index(drop=True)
    log.insert(2, "rank", log.groupby("month").cumcount() + 1)
    log.to_csv(LOG, index=False)
    return log, cfg, df


def table(log, df):
    last = log[log.month == log.month.max()]
    print(f"\nREAL ASSETS — LISTED REITs / SM-REITs / InvITs {log.month.max()} (1 = cheap/buy, 100 = rich/sell)")
    print(last[["rank", "key", "family", "oscillator", "signal", "valuation", "filter", "timing", "dist_yield_pct",
                "spread_vs_gsec_pp", "price_to_nav", "dpu_yoy_pct", "post_tax_yield_pct", "indicators_live"]].to_string(index=False))
    fam = last.groupby("family").agg(median_osc=("oscillator", "median"), median_yield=("dist_yield_pct", "median"),
                                     n=("key", "count")).round(2)
    print("\nBy family (median):"); print(fam.to_string())
    reits = last[last.family.isin(["Office REIT", "Retail REIT"]) & last.mcap_cr.notna()]
    if not reits.empty:
        wy = (reits.dist_yield_pct*reits.mcap_cr).sum()/reits.mcap_cr.sum()
        print(f"\nListed-REIT market-cap-weighted distribution yield: {wy:.2f}%  "
              f"(median {reits.dist_yield_pct.median():.2f}%) -> candidate value for asset-classes `reit_yield`")
        wn = reits.dropna(subset=["price_to_nav"])
        if not wn.empty:
            print(f"Listed-REIT market-cap-weighted price/NAV: {(wn.price_to_nav*wn.mcap_cr).sum()/wn.mcap_cr.sum():.2f}x ({len(wn)} REITs with NAV)")
    inv = last[last.family.str.contains("InvIT") & last.mcap_cr.notna()]
    if not inv.empty:
        print(f"Listed-InvIT market-cap-weighted distribution yield: {(inv.dist_yield_pct*inv.mcap_cr).sum()/inv.mcap_cr.sum():.2f}%")


